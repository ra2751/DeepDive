"""
Build evals/results/SUMMARY.md from RECORDED live result files only (no numbers are typed in).

Re-runs (e.g. L08-r1) are kept as separate observations of the same question and are not counted
as independent questions.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals" / "results"
# Stage label -> recorded run id (files are never modified by this script)
RUNS = [("Stage A", "20261017T073355Z_9a16a91"), ("Stage B · B1", "20261017T085933Z_9a16a91"),
        ("Stage B · B2", "20261017T090029Z_9a16a91"), ("Stage B · B3", "20261017T090136Z_9a16a91")]


def load():
    obs = []
    for stage, rid in RUNS:
        run = json.loads((RESULTS / f"{rid}.json").read_text())
        details = json.loads((RESULTS / f"{rid}_details.json").read_text())
        for c in run["cases"]:
            obs.append({"stage": stage, "run": rid, "commit": run["git_commit"], "dirty": run.get("git_dirty"),
                        "code": (run.get("code_sha256") or "")[:12], "case": c, "details": details.get(c["case_id"], {})})
    return obs


def base_id(case_id):
    return case_id.split("-r")[0]


def summarize(obs):
    questions = {}
    for o in obs:
        questions.setdefault(base_id(o["case"]["case_id"]), []).append(o)
    first = {q: v[0] for q, v in questions.items()}
    latest = {q: v[-1] for q, v in questions.items()}
    fc = [o for o in first.values() if o["case"]["mode"] == "fact_check"]
    fc_agree = sum(1 for o in fc if o["case"]["passed"])
    sentences = sum(o["case"]["verified_sentences"] for o in obs)
    leakage = sum(o["case"]["unsupported_claim_leakage"] for o in obs)
    citations = sum(len(o["details"].get("citations") or []) for o in obs)
    issues = sum(o["case"]["citation_integrity_issues"] for o in obs)
    mesh = sum(o["case"]["usage"]["mesh_llm_calls"] + o["case"]["usage"]["mesh_embedding_calls"] for o in obs)
    cost = sum(o["case"]["usage"]["cost_usd"] or 0 for o in obs)
    fns = [o for o in first.values() if o["case"]["mode"] == "fact_check"
           and o["case"]["expected"].get("C1") == ["supported"] and o["case"]["observed"].get("C1") != "supported"]
    return {"questions": len(questions), "observations": len(obs),
            "first_pass": sum(o["case"]["passed"] for o in first.values()),
            "latest_pass": sum(o["case"]["passed"] for o in latest.values()),
            "fc_agree": fc_agree, "fc_total": len(fc), "sentences": sentences, "leakage": leakage,
            "citations": citations, "issues": issues, "mesh": mesh, "cost": cost, "false_negatives": fns,
            "questions_map": questions}


def rejection_examples(obs, limit=8):
    out = []
    for o in obs:
        for cid, v in (o["details"].get("verifications") or {}).items():
            for r in v.get("rejected", []):
                if r.get("quote"):
                    out.append((o["case"]["case_id"], cid, r["stance"], r["reason"], r.get("source"), r.get("page"),
                                r["quote"]))
    return out[:limit]


def render(obs, s):
    L = ["# DeepDive live evaluation summary", "",
         "Generated by `python -m evals.summarize_results` from the recorded result files listed below. "
         "**Small sample: these numbers describe observed behaviour, not statistically reliable accuracy.**", "",
         "## Headline", "",
         "| Measure | Result |", "|---|---|",
         f"| Labelled questions evaluated | {s['questions']} ({s['observations']} observations; L08-r1 is a re-run of L08, not a separate question) |",
         f"| Questions passing on first attempt | {s['first_pass']} / {s['questions']} |",
         f"| Questions passing on latest attempt | {s['latest_pass']} / {s['questions']} (L08 passed only after the Stage A remediation) |",
         f"| Fact-check claim-status agreement (first attempt) | {s['fc_agree']} / {s['fc_total']} |",
         f"| Unsupported-claim leakage (verified sentences citing a non-supported claim) | {s['leakage']} / {s['sentences']} sentences |",
         f"| Citation-integrity failures | {s['issues']} across {s['citations']} citations |",
         f"| False negatives (labelled-true claim not verified) | {len(s['false_negatives'])}: "
         + (", ".join(o['case']['case_id'] for o in s['false_negatives']) or "none") + " |",
         f"| Mesh requests (all observations) | {s['mesh']} |",
         f"| Estimated cost (all observations) | ≈ US${s['cost']:.4f} (estimated, incomplete: Gemini reasoning tokens unpriced; "
         "includes 3 Stage B responses served from Mesh's cache, which Mesh documents as not billed) |", "",
         "## Observations", "",
         "| Stage | Case | Mode | Expected | Observed | Pass | Mesh req. | Latency | Est. cost |",
         "|---|---|---|---|---|---|---|---|---|"]
    for o in obs:
        c = o["case"]; u = c["usage"]
        exp = "; ".join(f"{k}: {'/'.join(v) if isinstance(v, list) else v}" for k, v in c["expected"].items())
        got = "; ".join(f"{k}: {v}" for k, v in c["observed"].items() if k != "citation_sources")
        L.append(f"| {o['stage']} | {c['case_id']} | {c['mode']} | {exp} | {got} | {'yes' if c['passed'] else '**no**'} | "
                 f"{u['mesh_llm_calls'] + u['mesh_embedding_calls']} | {u['elapsed_s']:.1f} s | "
                 f"{'n/a' if u['cost_usd'] is None else f'{u['cost_usd']:.4f}'} |")
    L += ["", "## What failed and why", "",
          "- **L08 (Stage A)** — all 11 report sentences were removed by DeepDive's own citation check (claim "
          "markers such as \"(C3)\" read as numbers). Fixed in the Stage A remediation; **L08-r1** then passed "
          "with 7 verified sentences. The Stage A failure is retained.",
          "- **L06** — labelled-true claim ended *unresolved*: the abstract stating the taxonomy was not retrieved "
          "and the only proposed quote failed the key-term rule (overlap 0.33 < 0.34). A false negative, not leakage.",
          "", "## Unsupported claims correctly rejected (examples)", "",
          "- **L02** \"The Transformer relies on recurrent layers in its encoder\" → *contradicted* by AttentionAllYouNeed.pdf p.3.",
          "- **L05** \"trained on 64 TPU chips\" and **L07** \"survey published in 2010\" → *unresolved*, never verified.",
          "- **L09** personal dosing question → *out of scope*, no research performed.",
          "- **L10** procurement question over an index with no procurement documents → *no verified findings* "
          "(evidence-absence statements were never reported as findings).", ""]
    ex = rejection_examples(obs)
    if ex:
        L += ["Rejected verifier proposals (recorded quote and reason):", ""]
        L += [f"- {case} {cid} ({stance}) {src} p.{page}: \"{q[:120]}\" — `{reason}`" for case, cid, stance, reason, src, page, q in ex]
        L.append("")
    L += ["## Source files", ""]
    L += [f"- `{rid}` ({stage}): commit {next(o['commit'] for o in obs if o['run'] == rid)}, uncommitted changes "
          f"{next(o['dirty'] for o in obs if o['run'] == rid)}, code fingerprint {next(o['code'] for o in obs if o['run'] == rid)}…"
          for stage, rid in RUNS]
    return "\n".join(L) + "\n"


def main():
    obs = load()
    s = summarize(obs)
    (RESULTS / "SUMMARY.md").write_text(render(obs, s))
    print(f"questions={s['questions']} observations={s['observations']} first_pass={s['first_pass']} "
          f"latest_pass={s['latest_pass']} fc={s['fc_agree']}/{s['fc_total']} leakage={s['leakage']}/{s['sentences']} "
          f"citations={s['citations']} issues={s['issues']} mesh={s['mesh']} cost={s['cost']:.4f}")


if __name__ == "__main__":
    sys.exit(main())
