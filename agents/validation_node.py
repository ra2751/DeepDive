logger = setup_logger()

def format_docs(docs):
    return "\n\n".join(
        [f"Source: {doc['source']}\nContent:{doc['content']}" for doc in docs]
        )

def ValidationAgent(state:AgentRagState):

    """
    The ValidationAgent's role is to evaluate the answer generated by the RagAgent 
    against the retrieved documents and the original query. 
    It determines whether the answer is valid 
    (i.e., grounded in the retrieved documents and addresses the query) 
    and provides reasoning for its evaluation.
    """
    
    question = state['query']

    #logger.info(f"validation Agent| Question: {question} ")
        
    # Defensive check: ensure messages exist before grabbing the last one
    messages = state.get('messages', [])


    if not messages:
        logger.info("validation Agent| Warning: No messages found in state to validate!")
        return {
            "validation_metadata": {"is_valid": "no", "reasoning": "No generation found to evaluate."}
        }
    generated_answer = messages[-1].content  # Get the content of the last message
    retrieved_docs = state.get('retrieved_docs',[]) 

    # Evaluate criteria if no documents exist
    if not retrieved_docs:
        # Case: GeneralLLMAgent
        formatted_docs = "N/A- This task did not require external documentation"
        criteria = "Is the generated answer a highly logical, accurate, " \
        "and direct response to the user's query?"
    else:
        # case: RagAgent or WebSearchAgent
        formatted_docs = format_docs(retrieved_docs)
        criteria = "Is the generated answer strictly grounded in the retrieved documents and " \
        "does it directly address the user's query?"

    # Create a prompt template that incorporates the query, generated answer, and retrieved documents
    template = """
    You are an independent quality assurance evaluator checking an AI's agent work.

    User Query: {question}

    Generated Answer:
    {generated_answer}

    Retrieved Documents:
    {formatted_docs}

    ### Evaluation criteria 
    {criteria}

    ### Strict Guardrails for Validation:
    1. If the 'Generated Answer' states that the information is missing, not found, or not available in the provided documents, 
    you MUST evaluate this as NOT valid ('no').
    2. An admission of missing information (e.g., "I cannot find this in the documents", "The retrieved text does not mention this") 
    is an automatic failure. It does NOT count as a valid response to the user's query.
    3. To be valid ('yes'), the answer must fully answer the user query using concrete information grounded in the retrieved documents.

    Is the generated answer valid? 
    A valid answer is one that is grounded in the retrieved documents where applicable 
    and directly addresses the user's query. 
    Please respond with 'yes' or 'no' and provide a brief reasoning for your evaluation.

    ### Critical rule for code validation:
    If the user query asks for code implementation templates, step-by-step programming scripts, or framework examples, 
    the use of semantic code placeholders (such as model_name = "MODEL_ID" or dataset = "DATASET_NAME") is VALID and acceptable. 
    Do not reject code scripts solely because they use standard placeholder variables, 
    provided the code architecture itself is complete and correct.

    """

    prompt = PromptTemplate.from_template(template)

    # using different model for evaluation to avoid bias from the generation step
    

    # Combine the prompt and model into a single chain
    chain = prompt | structured_model

    validation_response = chain.invoke({
        "question": question,
        "generated_answer": generated_answer,
        "formatted_docs": formatted_docs,
        "criteria": criteria
        })


    logger.info(f"ValidationAgent|evaluation results: Is Valid: {validation_response.is_valid} | Reasoning: {validation_response.reasoning}") 
    #logger.info(f"validationAgent | validation_response executed successfully")

    return {
        "validation_metadata": {
        "is_valid": validation_response.is_valid.lower().strip(),  # Ensure the output is in lowercase and remove any extra quotes
        "reasoning": validation_response.reasoning
        },
        "next_step": ""
    }

