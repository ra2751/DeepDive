class ValidationOutput(BaseModel):
    is_valid: str = Field(..., description=" 'yes' if answer is grounded in the docs, 'no' otherwise.")
    reasoning: str = Field(..., description="Brief explanation of why the answer is or is not valid.")

model = ChatGoogleGenerativeAI(model='gemini-2.5-flash', temperature=0)
structured_model = model.with_structured_output(ValidationOutput)
